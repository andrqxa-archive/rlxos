package font

import "avyos.dev/pkg/graphics/core"

type (
	Buffer = core.Buffer
	Color  = core.Color
)

var (
	ColorTransparent = core.ColorTransparent
	ColorWhite       = core.ColorWhite
	NewBuffer        = core.NewBuffer
)

type textRenderer interface {
	DrawText(buf *Buffer, text string, x, y int, fg, bg Color)
	DrawGlyph(buf *Buffer, r rune, x, y int, fg, bg Color)
	TextWidth(text string) int
	TextHeight(text string) int
}

// Font represents either a bitmap font or a vector TTF-backed font.
type Font struct {
	Width    int
	Height   int
	Glyphs   map[rune][]byte
	FirstRun rune
	LastRun  rune
	renderer textRenderer
}

// BitmapFont is the built-in 8x16 bitmap font.
var BitmapFont = &Font{
	Width:    8,
	Height:   16,
	FirstRun: 32,
	LastRun:  126,
	Glyphs:   defaultGlyphs,
}

// DefaultFont is the active font used by graphics and UI.
var DefaultFont = BitmapFont

// DrawText draws text to a buffer at the given position.
func (f *Font) DrawText(buf *Buffer, text string, x, y int, fg, bg Color) {
	if f == nil || buf == nil || text == "" {
		return
	}
	if f.renderer != nil {
		f.renderer.DrawText(buf, text, x, y, fg, bg)
		return
	}

	cx := x
	for _, r := range text {
		if r == '\n' {
			cx = x
			y += f.Height
			continue
		}
		f.DrawGlyph(buf, r, cx, y, fg, bg)
		cx += f.Width
	}
}

// DrawGlyph draws a single character glyph to a buffer.
func (f *Font) DrawGlyph(buf *Buffer, r rune, x, y int, fg, bg Color) {
	if f == nil || buf == nil {
		return
	}
	if f.renderer != nil {
		f.renderer.DrawGlyph(buf, r, x, y, fg, bg)
		return
	}

	glyph, ok := f.Glyphs[r]
	if !ok {
		glyph = f.Glyphs['?']
		if glyph == nil {
			return
		}
	}

	for row := 0; row < f.Height; row++ {
		if row >= len(glyph) {
			break
		}
		bits := glyph[row]
		for col := 0; col < f.Width; col++ {
			if bits&(0x80>>col) != 0 {
				buf.SetPixel(x+col, y+row, fg)
			} else if bg.A > 0 {
				buf.SetPixel(x+col, y+row, bg)
			}
		}
	}
}

// TextWidth returns the width of text in pixels.
func (f *Font) TextWidth(text string) int {
	if f == nil {
		return 0
	}
	if f.renderer != nil {
		return f.renderer.TextWidth(text)
	}

	maxWidth := 0
	width := 0
	for _, r := range text {
		if r == '\n' {
			if width > maxWidth {
				maxWidth = width
			}
			width = 0
		} else {
			width += f.Width
		}
	}
	if width > maxWidth {
		maxWidth = width
	}
	return maxWidth
}

// TextHeight returns the height of text in pixels.
func (f *Font) TextHeight(text string) int {
	if f == nil {
		return 0
	}
	if f.renderer != nil {
		return f.renderer.TextHeight(text)
	}

	lines := 1
	for _, r := range text {
		if r == '\n' {
			lines++
		}
	}
	return lines * f.Height
}

