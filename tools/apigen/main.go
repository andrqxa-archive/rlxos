type uint16Value uint16
type uint32Value uint32

func (v *uint16Value) UnmarshalJSON(data []byte) error {
	n, err := parseFlexibleUint(data, 16)
	if err != nil {
		return err
	}
	*v = uint16Value(n)
	return nil
}

func (v *uint32Value) UnmarshalJSON(data []byte) error {
	n, err := parseFlexibleUint(data, 32)
	if err != nil {
		return err
	}
	*v = uint32Value(n)
	return nil
}

func parseFlexibleUint(data []byte, bits int) (uint64, error) {
	data = bytes.TrimSpace(data)
	if len(data) == 0 {
		return 0, errors.New("empty numeric value")
	}
	if data[0] == '"' {
		var s string
		if err := json.Unmarshal(data, &s); err != nil {
			return 0, err
		}
		s = strings.TrimSpace(s)
		if s == "" {
			return 0, errors.New("empty numeric string")
		}
		return strconv.ParseUint(s, 0, bits)
	}
	return strconv.ParseUint(string(data), 10, bits)
}

type apiSpec struct {
	Service  serviceSpec  `json:"service"`
	Imports  []string     `json:"imports,omitempty"`
	Types    []typeSpec   `json:"types,omitempty"`
	Requests []methodSpec `json:"requests,omitempty"` // client -> server
	Events   []methodSpec `json:"events,omitempty"`   // server -> client
}

type serviceSpec struct {
	Name    string      `json:"name"`
	ID      uint32Value `json:"id"`
	Package string      `json:"package,omitempty"` // defaults to api/<name> dir name
}

type typeSpec struct {
	Name   string      `json:"name"`
	Fields []fieldSpec `json:"fields,omitempty"`
}

type methodSpec struct {
	Name         string      `json:"name"`
	ID           uint16Value `json:"id"`
	RequestType  string      `json:"request_type,omitempty"`
	ResponseType string      `json:"response_type,omitempty"`
	PayloadType  string      `json:"payload_type,omitempty"` // alias for request_type
	OneWay       bool        `json:"one_way,omitempty"`
	Comment      string      `json:"comment,omitempty"`
}

type fieldSpec struct {
	Name string `json:"name"`
	Type string `json:"type"`
}

type methodInfo struct {
	Name               string
	RequestID          uint16
	RequestConst       string
	EventConst         string
	RequestType        string
	ResponseType       string
	ServerRequestType  string
	ServerResponseType string
	OneWay             bool
	Comment            string
}

type typeInfo struct {
	Name   string
	Fields []fieldInfo
}

type fieldInfo struct {
	Name      string
	Type      string
	EncMethod string // encoder method, e.g. "PutUint32"
	DecMethod string // decoder method, e.g. "Uint32"
	EncCast   string // cast wrapper for encoding, e.g. "int" → enc.PutInt(int(v.X))
	DecCast   string // cast wrapper for decoding, e.g. "graphics.Key" → v.Key = graphics.Key(dec.Int())
	IsSlice   bool   // true for []T fields
	SliceElem string // element type if IsSlice (e.g. "WindowListItem")
}

